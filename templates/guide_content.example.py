# -*- coding: utf-8 -*-
"""測試指引內容範例：複製成工作資料夾的 guide_content.py，照 TG2 核准的大綱改寫（references/test-guide.md）。
Phase 0 選了「測試指引」才做。A4 直式、獨立一份 PDF，不和 16:9 簡報合成。

讀者是要動手測的人：拿到就知道用哪個身分登入、照什麼步驟做、每一步應該看到什麼、怎麼打勾、不對時怎麼回報。
**每一步的預期畫面都要是自己照著走過一遍確認的**（TG4），不能從程式碼推測就寫上去。

執行：python guide_content.py → 「AI GO 租戶名 App名 測試指引 YYYYMMDD.html」
      node <skill>/scripts/render.mjs --html "AI GO … 測試指引 ….html" --png preview   → 同名 A4 PDF
頁序固定（寫的順序不影響）：封面 → 目錄 → 測試準備 → 身分與帳號 → 怎麼執行 → 測試流程 → 權限檢查 → 判定標準 → 回報方式
→ 總檢查清單 → 問題回報單 → 送出前確認。目錄、怎麼執行、判定標準、兩張表單、封底沒寫就自動產生。
"""
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent / "scripts"      # 放到工作資料夾後，改成 skill 的 scripts 路徑
sys.path.insert(0, str(SKILL))
from guide_kit import Guide  # noqa: E402

# 租戶名、App 名由 discover.mjs 寫進 disc/meta.json；site＝測試站網址（印在封面與測試準備）
g = Guide.from_meta("disc/meta.json", shots="shots", version="VFS v12",
                    site="https://demo.ai-go.app/apps/order-center", audience="門市店長、客服與倉管")

# ── 封面（可省略）：三個目標、製作日、範圍（N 種身分・M 條流程）自動帶 ──
g.cover("這份指引帶你用三種身分，把訂單從建立到出貨走一遍；<br>每一步對照預期畫面，不符合就回報。")

# ── 測試準備：env＝環境資訊；todo 省略＝通用清單；dont＝絕對不要做的事（深底注意框）──
g.prepare(env=[("測試期間", "2026/11/03（一）～11/07（五）"),
               ("瀏覽器", "桌機 Chrome 最新版；手機版不在這次範圍"),
               ("測試資料", "客人名稱以「TEST-」開頭的才可以改；其他資料只看不改")],
          dont=["不要按「推播給全部客人」——會真的發 LINE 給客人",
                "不要刪除不是「TEST-」開頭的訂單"])

# ── 身分與帳號（必填）：(身分, 帳號代碼, 平常做什麼, 這次測試重點)。密碼私下給，不寫進來 ──
g.roles([("店長", "店長-1", "看全店訂單、改價、退款", "建立與修改訂單、退款審核"),
         ("客服", "客服-1", "回覆客人、查訂單", "查詢訂單、看不到退款按鈕"),
         ("倉管", "倉管-1", "出貨、更新物流", "出貨流程、看不到金額")])

# ── 測試流程（至少一條；一條一頁）── steps＝(操作, 預期畫面)，每一步都要有預期畫面。
# 操作寫畫面上的字一字不差（按鈕、欄位、分頁名）；預期寫做完應該看到什麼（提示、列表、狀態），不寫「正常」「成功」這種空話。
# shot＝預期畫面截圖（shoot.mjs 拍的，1～2 張），通常放流程最後的結果畫面。
g.flow("建立一筆訂單", role="店長", goal="從新增到列表看得到，金額與狀態正確。",
       pre="用「店長-1」登入；購物車是空的",
       steps=[("左側選單點「訂單」", "訂單列表出現，右上角有「新增訂單」按鈕"),
              ("點「新增訂單」", "右側滑出「新增訂單」表單，所有欄位空白"),
              ("客人選「TEST-王小明」，商品選「護膝 M」數量 2", "下方「小計」顯示 NT$ 2,400"),
              ("點「建立」", "右上角跳出綠色提示「訂單已建立」，表單關閉"),
              ("看列表第一列", "出現剛建立的訂單：客人 TEST-王小明、金額 NT$ 2,400、狀態「待付款」")],
       shot="order-created", caption="步驟 5 完成後的列表：第一列是剛建立的訂單",
       passes="列表看得到新訂單，金額與狀態和預期相同。", fails="提示成功但列表沒有、金額不對、或出現錯誤訊息。",
       minutes=5)

g.flow("客服查詢訂單", role="客服", goal="客服查得到訂單，但看不到退款按鈕。",
       pre="T01 已完成；改用「客服-1」登入",
       steps=[("左側選單點「訂單」", "訂單列表出現；右上角沒有「新增訂單」按鈕"),
              ("搜尋框輸入「TEST-王小明」按 Enter", "只剩 TEST-王小明 的訂單"),
              ("點那筆訂單", "右側顯示訂單明細；下方只有「複製訂單編號」，沒有「退款」")],
       minutes=3)

# ── 權限檢查（選配）：每列＝(功能, 每個身分的預期)，身分順序同 roles()；短詞：可以／看不到／唯讀 ──
g.permissions([("新增訂單", "可以", "看不到", "看不到"),
               ("訂單金額", "可以", "可以", "看不到"),
               ("退款", "可以", "看不到", "看不到"),
               ("更新物流單號", "可以", "唯讀", "可以")])

# ── 判定標準（可省略）：critical＝這支 app 的重大問題，省略＝通用四項 ──
g.judge(critical=["客服或倉管看得到退款按鈕或金額", "訂單建立後列表沒有，或金額和小計不同",
                  "按出貨後客人沒收到出貨通知（或收到兩次）"])

# ── 回報方式（必填）：回報到哪裡、給誰、期限；sla 只寫 FDE 承諾得了的回覆時效 ──
g.report(channel="LINE 群組「訂單中心測試回報」", to="王小明（FDE）", deadline="11/07（五）18:00 前",
         sla={"高": "當天回覆", "中": "2 個工作天內", "低": "下一次更新一起處理"})

# ── 送出前確認（封底，可省略）──
g.back_cover(contact=["FDE 王小明"])

g.write()
